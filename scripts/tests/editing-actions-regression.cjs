const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('/Applications/DevEco-Studio.app/Contents/tools/hvigor/hvigor/node_modules/typescript');
const exported = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('entry/src/main/ets/core/LexiEditingActions.ets', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exported });
const edit = exported.LexiEditingActions;
let result = edit.apply('alpha beta', 0, 5, 'bold');
assert.equal(result.content, '**alpha** beta');
result = edit.apply(result.content, result.start, result.end, 'bold');
assert.equal(result.content, 'alpha beta');
assert.equal(edit.apply('- [ ] task', 4, 4, 'todo').content, '- [x] task');
assert.equal(edit.apply('- [x] task', 4, 4, 'todo').content, '- [ ] task');
assert.equal(edit.apply('### title', 5, 5, 'h2').content, '## title');
assert.equal(edit.apply('a\nb\nc', 2, 3, 'line-up').content, 'b\na\nc');
assert.equal(edit.apply('a\nb\nc', 2, 3, 'line-down').content, 'a\nc\nb');
const table = '| A | B |\n| --- | --- |\n| one | two |\n| three | four |';
let caret = table.indexOf('two');
assert.match(edit.table(table, caret, 'align-right').content, /\| --- \| ---: \|/);
assert.match(edit.table(table, caret, 'col-delete').content, /\| A \|\n\| --- \|\n\| one \|/);
assert.match(edit.table(table, caret, 'row-copy').content, /\| one \| two \|\n\| one \| two \|/);
assert.match(edit.table(table, caret, 'row-down').content, /\| three \| four \|\n\| one \| two \|/);
assert.equal(edit.cells('| a\\|b | `x|y` |').join(';'), 'a\\|b;`x|y`');
assert.throws(() => edit.table('```\n' + table + '\n```', 4 + caret, 'col-delete'), /表格/);
assert.throws(() => edit.table(table, 2, 'row-delete'), /数据行/);
assert.throws(() => edit.table('| A |\n| --- |\n| x |', 19, 'col-delete'), /至少保留/);
console.log('PASS reversible formatting, selection, task toggle, headings, line movement, table alignment, row/column edits, escaped cells and fenced-code protection');

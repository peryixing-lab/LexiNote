/**
 * Interface language is separate from note content, filenames, and plugin-owned copy.
 * Exact 1:1 port of LexiI18n.ets and LexiEnglish.ets.
 */
object LexiI18n {
    var currentLanguage: String = "zh-Hans"

    fun systemLanguage(): String {
        return try {
            val lang = Locale.getDefault().language.lowercase()
            if (lang.startsWith("en")) "en" else "zh-Hans"
        } catch (_: Exception) {
            "zh-Hans"
        }
    }

    fun language(): String {
        return if (currentLanguage == "en" || currentLanguage == "zh-Hans") {
            currentLanguage
        } else {
            systemLanguage()
        }
    }

    fun text(source: String, language: String = "", args: List<String> = emptyList()): String {
        val selected = language.ifEmpty { language() }
        var translated = if (selected == "en") (LEXI_ENGLISH[source] ?: source) else source
        for (index in args.indices) {
            translated = translated.replace("{$index}", args[index])
        }
        return translated
    }

